/**
 * The retail text type for a code, or null when the retail client printed
 * nothing for it (no switch arm, or a notice-only arm).
 */
export function weenieErrorTextType(code: number): number | null {
  return WEENIE_ERROR_TEXT_TYPE[code] ?? null;
}

export type WeenieErrorSink = 'spew' | 'chat' | 'none';

/** spew (0x1a) | chat (any other text type) | none (retail printed nothing). */
export function weenieErrorSink(code: number): WeenieErrorSink {
  const type = weenieErrorTextType(code);
  if (type === null) return 'none';
  return type === WEENIE_ERROR_TEXT_TYPE_SPEW ? 'spew' : 'chat';
}
