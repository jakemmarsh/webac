/** One function's help line: `name[args]: description`, or null when there is no such function. */
export function exprFunctionHelp(name: string): string | null {
  const key = name.trim().replace(/\[.*$/, '').toLowerCase();
  if (!EXPR_FUNCTIONS.includes(key)) return null;
  const [args, text] = HELP[key] ?? ['', ''];
  return `${key}[${args}]: ${text}`.trimEnd();
}

/** Every function that has no help line (a test keeps this empty). */
export function exprFunctionsWithoutHelp(): string[] {
  return EXPR_FUNCTIONS.filter((f) => !HELP[f]);
}
