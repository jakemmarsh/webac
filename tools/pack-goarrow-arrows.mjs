#!/usr/bin/env node
/**
 * Pack GoArrow's arrow frames (MIT art: Copyright (c) 2007 Ben Howell; (c) 2018 Xanius;
 * docs/plugin-specs/goarrow.md §1.1, §8) into one sprite sheet per set for the arrow HUD
 * (packages/renderer/src/ui/goarrow/arrows/).
 *
 * Usage: node tools/pack-goarrow-arrows.mjs <dir Arrows.zip was unzipped into> <out dir> [set,set,...]
 *
 * We ship Chrome (the default) and Simple: the other three sets are 250–525 KB each as sheets.
 * Pass their names to add them (e.g. `Chrome,Simple,Red Glass`).
 *
 * Treat the zip as untrusted data: unzip it into a fresh empty directory and run this script from
 * elsewhere (it only decodes PNGs with pngjs). Each set `<Set>/arrow_fNN.png` (frames 1..N, no gaps,
 * all one size) becomes `<slug>.png`, frames left to right then top to bottom in `cols` columns, and
 * the manifest `sheets.ts` records each set's frame size, count and columns, with a literal
 * `new URL('./<slug>.png', import.meta.url)` per set so Vite emits each sheet as an asset and the
 * browser fetches only the set in use.
 */
import fs from 'node:fs';
import path from 'node:path';
import { PNG } from 'pngjs';

const [src, out, only] = process.argv.slice(2);
const wanted = only ? new Set(only.split(',').map((x) => x.trim().toLowerCase())) : null;
if (!src || !out) { console.error('usage: pack-goarrow-arrows.mjs <unzipped Arrows.zip dir> <out dir>'); process.exit(1); }
fs.mkdirSync(out, { recursive: true });

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const manifest = {};
for (const set of fs.readdirSync(src).sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }))) {
  const dir = path.join(src, set);
  if (!fs.statSync(dir).isDirectory() || (wanted && !wanted.has(set.toLowerCase()))) continue;
  const frames = [];
  for (let i = 1; ; i++) {
    const f = path.join(dir, `arrow_f${String(i).padStart(2, '0')}.png`);
    if (!fs.existsSync(f)) break;
    frames.push(PNG.sync.read(fs.readFileSync(f)));
  }
  if (!frames.length) continue;
  const { width: w, height: h } = frames[0];
  if (frames.some((p) => p.width !== w || p.height !== h)) throw new Error(`${set}: frames differ in size`);
  const cols = Math.min(frames.length, Math.max(1, Math.floor(1024 / w)));
  const rows = Math.ceil(frames.length / cols);
  const sheet = new PNG({ width: cols * w, height: rows * h });
  sheet.data.fill(0);
  frames.forEach((p, i) => PNG.bitblt(p, sheet, 0, 0, w, h, (i % cols) * w, Math.floor(i / cols) * h));
  const file = `${slug(set)}.png`;
  fs.writeFileSync(path.join(out, file), PNG.sync.write(sheet, { deflateLevel: 9 }));
  manifest[set] = { file, frames: frames.length, width: w, height: h, cols };
  console.log(`${set}: ${frames.length} frames ${w}x${h} -> ${file} ${cols}x${rows} (${fs.statSync(path.join(out, file)).size} bytes)`);
}
const lines = [
  '// Generated by tools/pack-goarrow-arrows.mjs; do not edit.',
  "// GoArrow's arrow art: MIT, Copyright (c) 2007 Ben Howell; (c) 2018 Xanius (docs/plugin-specs/goarrow.md §8).",
  '',
  'export interface GoArrowSheet {',
  '  name: string;',
  '  frames: number;',
  '  width: number;',
  '  height: number;',
  '  /** Frames per row; frame i is at column i % cols, row floor(i / cols). */',
  '  cols: number;',
  '  /** The sheet\'s URL (Vite emits the PNG as an asset; nothing loads until this is called). */',
  '  url(): string;',
  '}',
  '',
  '/** Every packed set, in the "Arrow image" dropdown\'s case-insensitive order. */',
  'export const GOARROW_SHEETS: readonly GoArrowSheet[] = [',
  ...Object.entries(manifest).map(([name, m]) => `  { name: '${name.replace(/'/g, "\\'")}', frames: ${m.frames}, width: ${m.width}, height: ${m.height}, cols: ${m.cols}, url: () => new URL('./${m.file}', import.meta.url).href },`),
  '];',
  '',
];
fs.writeFileSync(path.join(out, 'sheets.ts'), lines.join('\n'));
