function main(): void {
  const cs = readFileSync(CS_PATH, 'utf8');
  const entries = parseEnum(cs);

  if (entries.length < 300) {
    console.error(`Sanity check failed: only ${entries.length} entries parsed. Expected 300+.`);
    process.exit(1);
  }

  // Sanity: known anchor entries.
  const byName = new Map(entries.map((e) => [e.name, e]));
  const anchors: Array<[string, number]> = [
    ['None', 0x0000],
    ['NoPhysicsObject', 0x0008],
    ['ActionCancelled', 0x0036],
    ['YourSpellFizzled', 0x0402],
    ['ContractError', 0x0594],
  ];
  for (const [n, v] of anchors) {
    const e = byName.get(n);
    if (!e || e.value !== v) {
      console.error(`Anchor failed: ${n} expected 0x${v.toString(16)}, got ${e?.value.toString(16)}`);
      process.exit(1);
    }
  }

  const out = emit(entries);
  writeFileSync(TS_PATH, out);

  const withText = entries.filter((e) => e.text).length;
  console.log(
    `Wrote ${TS_PATH}\n  ${entries.length} enum entries\n  ${withText} text mappings (from <summary> tags)`,
  );
}

main();
