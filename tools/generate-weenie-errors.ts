interface Entry {
  name: string;
  value: number;
  text: string | null;
  comment: string | null; // // Client side only, // Skip 1, etc.
}

function parseEnum(source: string): Entry[] {
  const lines = source.split('\n');
  const entries: Entry[] = [];

  // Accumulate <summary> text + raw // comments until we see an enum line.
  let pendingSummary: string[] | null = null;
  let inSummary = false;
  let pendingComment: string | null = null;

  // matches:  Identifier = 0xNNNN,
  // matches:  Identifier = 0xNNNN
  const enumLineRe = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*0x([0-9A-Fa-f]+)\s*,?\s*$/;

  for (const rawLine of lines) {
    const line = rawLine.replace(/\r$/, '');
    const trimmed = line.trim();

    // <summary> block start
    if (trimmed === '/// <summary>') {
      pendingSummary = [];
      inSummary = true;
      continue;
    }
    // <summary> block end
    if (trimmed === '/// </summary>') {
      inSummary = false;
      continue;
    }
    if (inSummary) {
      // strip leading "/// "
      const m = /^\s*\/\/\/\s?(.*)$/.exec(line);
      if (m) pendingSummary!.push(m[1]);
      continue;
    }

    // line comment (e.g. "// Client side only", "// Skip 1")
    if (/^\s*\/\//.test(line)) {
      pendingComment = trimmed.replace(/^\/\/\s?/, '');
      continue;
    }

    // enum entry
    const em = enumLineRe.exec(line);
    if (em) {
      const name = em[1];
      const value = parseInt(em[2], 16);
      const text = pendingSummary
        ? pendingSummary
            .map((s) => s.trim())
            .filter((s) => s.length > 0)
            .join(' ')
            .trim() || null
        : null;
      entries.push({ name, value, text, comment: pendingComment });
      pendingSummary = null;
      pendingComment = null;
      continue;
    }

    // anything else clears pending comment but NOT pending summary if we're
    // still chained to it (some entries have <summary> + // comment + enum line)
    if (trimmed.length > 0) {
      pendingComment = null;
    }
  }

  return entries;
}

function escapeJsString(s: string): string {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n');
}

