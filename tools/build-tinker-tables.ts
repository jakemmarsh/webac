/**
 * UtilityBelt's Tinker tab, /ub tinkcalc and /ub autotinker (docs/vtank-parity-gaps.md §7) need to know, per
 * era, which salvage tinkers with which skill and which salvage imbues. One table per era, from that era's own
 * world data, so an era without tinkering (1999) has an empty one and says so:
 *
 *   end of retail  world-db-raw/ACE-World-16PY  "3-Core/4 CraftTable" SQL
 *   AC1999         reference/ac1999/Server/Database/AC1999-World (the same layout; it has no tinkering recipes)
 *   Dark Majesty   the ClassicACE CustomDM world in its MySQL container (recipe + cook_book)
 *
 * A tinkering recipe is one with a salvage_Type (ACE RecipeManager IsTinkering: SalvageType > 0; IsImbuing:
 * SalvageType == 2). Its skill is the recipe's (Weapon 28, Armor 29, Magic Item 30, Item 18 Tinkering), its
 * material the source bag's ("Salvaged Granite" → Granite, by ACE MaterialType name).
 *
 *   npx tsx tools/build-tinker-tables.ts [eol|ac1999|dm ...]
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { MATERIAL_NAMES } from '../packages/shared/src/loot/MaterialTypes.ts';

/** [materialType, skill, salvageType (1 tinker, 2 imbue)] */
export type TinkerRow = [number, number, number];

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'packages/renderer/src/agent/ub/tinker');

const BY_NAME = new Map(Object.entries(MATERIAL_NAMES).map(([id, n]) => [n.toLowerCase().replace(/\s+/g, ''), Number(id)]));

/** A salvage bag's material, from its name ("Salvaged Black Garnet", "Salvage (Granite)", "Granite Salvage"). */
export function bagMaterial(name: string): number | null {
  const m = /^Salvaged (.+)$/i.exec(name.trim()) ?? /^Salvage \((.+)\)$/i.exec(name.trim()) ?? /^(.+) Salvage$/i.exec(name.trim());
  if (!m) return null;
  return BY_NAME.get(m[1]!.toLowerCase().replace(/\s+/g, '')) ?? null;
}

function sqlFiles(dir: string): string[] {
  const out: string[] = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out.push(...sqlFiles(p));
    else if (p.endsWith('.sql')) out.push(p);
  }
  return out;
}

/** ACE-layout recipe SQL: the recipe's skill and salvage type, and every source bag in its cook book. */
export function parseTinkerSql(text: string): TinkerRow[] {
  const r = /INSERT INTO `recipe` \([^)]*\)\s*VALUES \(\d+, *\d+, *(\d+)[^,]*, *\d+, *(\d+),/.exec(text);
  if (!r) return [];
  const [, skill, salvageType] = r;
  if (Number(salvageType) <= 0) return [];
  const book = /INSERT INTO `cook_book` \([^)]*\)\s*VALUES ([\s\S]*?);/.exec(text);
  if (!book) return [];
  const out: TinkerRow[] = [];
  for (const [, src] of book[1]!.matchAll(/\(\d+, *\d+ *\/\* *(.*?) *\*\/,/g)) {
    const mat = bagMaterial(src!);
    if (mat !== null) out.push([mat, Number(skill), Number(salvageType)]);
  }
  return out;
}

function fromSqlTree(dir: string): TinkerRow[] {
  return sqlFiles(dir).flatMap((f) => parseTinkerSql(readFileSync(f, 'utf8')));
}

function fromClassicAce(): TinkerRow[] {
  const pw = execFileSync('docker', ['exec', 'classicace-db', 'printenv', 'MYSQL_ROOT_PASSWORD'], { encoding: 'utf8' }).trim();
  const sql = (q: string): string[][] => execFileSync('docker', ['exec', 'classicace-db', 'mysql', '-uroot', `-p${pw}`, '-N', '-B', 'ace_world_customdm', '-e', q], { encoding: 'utf8', maxBuffer: 64 << 20 })
    .trim().split('\n').filter(Boolean).map((l) => l.split('\t'));
  // Two plain reads, as build-craft-tables: the recipes' source bags, then every name.
  const pairs = sql('SELECT DISTINCT r.skill, r.salvage_Type, c.source_W_C_I_D FROM recipe r JOIN cook_book c ON c.recipe_Id = r.id WHERE r.salvage_Type > 0');
  const names = new Map(sql('SELECT object_Id, value FROM weenie_properties_string WHERE type = 1').map(([id, v]) => [id, v]));
  return pairs.flatMap(([skill, st, src]) => {
    const mat = bagMaterial(names.get(src!) ?? '');
    return mat === null ? [] : [[mat, Number(skill), Number(st)] as TinkerRow];
  });
}

/** One row per material: its skill and whether it imbues (a material tinkering and imbuing keeps both rows). */
export function compactRows(all: TinkerRow[]): TinkerRow[] {
  const seen = new Map<string, TinkerRow>();
  for (const r of all) seen.set(r.join(','), r);
  return [...seen.values()].sort((a, b) => a[0] - b[0] || a[2] - b[2] || a[1] - b[1]);
}

function write(era: string, all: TinkerRow[]): void {
  const rows = compactRows(all);
  writeFileSync(join(OUT, `${era}.ts`), `// Generated by tools/build-tinker-tables.ts from this era's world data; do not edit.\n// [materialType, skill, salvageType (1 tinker, 2 imbue)]\nexport default ${JSON.stringify(JSON.stringify(rows))};\n`);
  console.log(`${era}: ${rows.length} material rows from ${all.length} recipe bags`);
}

// Run only as a script (tests import the parsers without regenerating anything).
const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename);
const want = process.argv.slice(2);
const eras = !isMain ? [] : want.length ? want : ['eol', 'ac1999', 'dm'];
for (const era of eras) {
  if (era === 'eol') write('eol', fromSqlTree(join(ROOT, 'world-db-raw/ACE-World-16PY/Database/3-Core/4 CraftTable')));
  else if (era === 'ac1999') write('ac1999', fromSqlTree(join(ROOT, 'reference/ac1999/Server/Database/AC1999-World/3-Core/4 CraftTable')));
  else if (era === 'dm') write('dm', fromClassicAce());
}
