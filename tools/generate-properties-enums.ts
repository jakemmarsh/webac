/**
 * Parse ACE Properties enum files and regenerate
 * packages/shared/src/weenie-types.ts with the FULL enum coverage anchored
 * to current ACE source.
 *
 * Source files:
 *   reference/ACE/Source/ACE.Entity/Enum/Properties/PropertyInt.cs
 *   reference/ACE/Source/ACE.Entity/Enum/Properties/PropertyBool.cs
 *   reference/ACE/Source/ACE.Entity/Enum/Properties/PropertyFloat.cs
 *   reference/ACE/Source/ACE.Entity/Enum/Properties/PropertyString.cs
 *   reference/ACE/Source/ACE.Entity/Enum/Properties/PropertyDataId.cs
 *   reference/ACE/Source/ACE.Entity/Enum/Properties/PropertyInstanceId.cs
 *
 * Also re-ports the WeenieType enum from reference/ACE/Source/ACE.Entity/Enum/WeenieType.cs.
 *
 * Run: `npx tsx tools/generate-properties-enums.ts`
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, '..');
const OUT_PATH = resolve(REPO, 'packages/shared/src/weenie-types.ts');

interface EnumEntry {
  name: string;
  value: number;
}

interface EnumDef {
  enumName: string;
  /** Path to ACE source for traceability. */
  source: string;
  entries: EnumEntry[];
}

const ACE_BASE = 'reference/ACE/Source/ACE.Entity/Enum';

const SOURCES: Array<{ enumName: string; csFile: string }> = [
  { enumName: 'PropertyInt', csFile: `${ACE_BASE}/Properties/PropertyInt.cs` },
  { enumName: 'PropertyBool', csFile: `${ACE_BASE}/Properties/PropertyBool.cs` },
  { enumName: 'PropertyFloat', csFile: `${ACE_BASE}/Properties/PropertyFloat.cs` },
  { enumName: 'PropertyString', csFile: `${ACE_BASE}/Properties/PropertyString.cs` },
  { enumName: 'PropertyDataId', csFile: `${ACE_BASE}/Properties/PropertyDataId.cs` },
  { enumName: 'PropertyInstanceId', csFile: `${ACE_BASE}/Properties/PropertyInstanceId.cs` },
  { enumName: 'PropertyInt64', csFile: `${ACE_BASE}/Properties/PropertyInt64.cs` },
  { enumName: 'WeenieType', csFile: `${ACE_BASE}/WeenieType.cs` },
];

function parseEnum(source: string, enumName: string, fullPath: string): EnumDef {
  const lines = source.split('\n');
  const entries: EnumEntry[] = [];

  // Explicit value:   EncumbranceVal = 5,
  // Auto-increment:   Generic,
  const explicitRe = /^\s*([A-Z][A-Za-z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+|-?\d+)\s*,?\s*(\/\/.*)?$/;
  const autoRe = /^\s*([A-Z][A-Za-z0-9_]*)\s*,?\s*(\/\/.*)?$/;

  let insideEnum = false;
  let nextAuto = 0;
  const enumOpenRe = new RegExp(`enum\\s+${enumName}\\b`);

  for (const rawLine of lines) {
    const line = rawLine.replace(/\r$/, '');

    if (!insideEnum) {
      if (enumOpenRe.test(line)) {
        insideEnum = true;
      }
      continue;
    }

    if (/^\s*}/.test(line)) break;

    const explicitMatch = explicitRe.exec(line);
    if (explicitMatch) {
      const name = explicitMatch[1];
      const valStr = explicitMatch[2];
      const value = valStr.startsWith('0x') ? parseInt(valStr, 16) : parseInt(valStr, 10);
      entries.push({ name, value });
      nextAuto = value + 1;
      continue;
    }

    // Skip blank lines, attributes ([SendOnLogin]), comments, etc.
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('//') || trimmed.startsWith('[') || trimmed.startsWith('/*') || trimmed.startsWith('*')) {
      continue;
    }

    const autoMatch = autoRe.exec(line);
    if (autoMatch) {
      const name = autoMatch[1];
      entries.push({ name, value: nextAuto });
      nextAuto++;
    }
  }

  return { enumName, source: fullPath, entries };
}

function emitEnum(def: EnumDef): string {
  const out: string[] = [];
  out.push(
    `/** ${def.enumName} — ${def.entries.length} entries. Source: ${def.source} */`,
    `export enum ${def.enumName} {`,
  );
  for (const e of def.entries) {
    out.push(`  ${e.name} = ${e.value},`);
  }
  out.push('}');
  return out.join('\n');
}

function emitFile(defs: EnumDef[]): string {
  const total = defs.reduce((acc, d) => acc + d.entries.length, 0);
  const header = [
    '/**',
    ' * Property enums from ACE.Entity.Enum.Properties + WeenieType from ACE.Entity.Enum.',
    ' *',
    ` * GENERATED by tools/generate-properties-enums.ts — ${total} total entries`,
    ` * across ${defs.length} enums. Re-run after any ACE rebase. Do not hand-edit.`,
    ' *',
    ' * The server sends these IDs in CreateObject, UpdatePropertyInt, IdentifyResponse,',
    ' * PlayerDescription, and many other GameEvent payloads. Each ID is wire-format',
    ' * load-bearing — drift means we mishandle or silently drop server updates.',
    ' */',
    '',
  ].join('\n');
  return header + defs.map(emitEnum).join('\n\n') + '\n';
}

function main(): void {
  const defs: EnumDef[] = [];
  for (const { enumName, csFile } of SOURCES) {
    const full = resolve(REPO, csFile);
    const src = readFileSync(full, 'utf8');
    const def = parseEnum(src, enumName, csFile);

    // Sanity: each enum should have at least 10 entries. PropertyInt64 is
    // genuinely sparse (13 entries) — most numeric stats are 32-bit ints.
    if (def.entries.length < 10) {
      console.error(`Sanity check failed for ${enumName}: only ${def.entries.length} entries parsed.`);
      process.exit(1);
    }
    defs.push(def);
    console.log(`  ${enumName}: ${def.entries.length} entries`);
  }

  // Sanity: anchor known values.
  const propInt = defs.find((d) => d.enumName === 'PropertyInt')!;
  const byName = new Map(propInt.entries.map((e) => [e.name, e.value]));
  const propIntAnchors: Array<[string, number]> = [
    ['Undef', 0],
    ['ItemType', 1],
    ['CreatureType', 2],
    ['EncumbranceVal', 5],
    ['Level', 25],
    ['HeritageGroup', 188],
    ['InventoryOrder', 9015],
  ];
  for (const [name, value] of propIntAnchors) {
    const v = byName.get(name);
    if (v !== value) {
      console.error(`PropertyInt anchor mismatch: ${name} expected ${value}, got ${v}`);
      process.exit(1);
    }
  }

  const out = emitFile(defs);
  writeFileSync(OUT_PATH, out);
  console.log(`Wrote ${OUT_PATH} — ${defs.reduce((a, d) => a + d.entries.length, 0)} total entries`);
}

main();
