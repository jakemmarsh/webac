/**
 * AGENT.vtank-crafting — the recipe tables the automation's crafting reads
 * (VirindiTank's AutoCraftItems: make a listed kit, food or ammunition from
 * its parts; docs/vtank-macro-behavior.md "Crafting"). One table per era, from
 * that era's own world data, so each era crafts what its server allows:
 *
 *   end of retail  world-db-raw/ACE-World-16PY  "3-Core/4 CraftTable" SQL
 *   AC1999         reference/ac1999/Server/Database/AC1999-World (the same layout)
 *   Dark Majesty   the ClassicACE CustomDM world in its MySQL container (recipe + cook_book)
 *
 * Kept: the skills VirindiTank crafts with (none, Fletching 37, Alchemy 38,
 * Cooking 39); tinkering, salvage and imbue recipes are left out.
 *
 *   npx tsx tools/build-craft-tables.ts [eol|ac1999|dm ...]
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';

export interface CraftRecipe {
  /** The item used ("source"), by name. */
  first: string;
  /** The item it is used on ("target"), by name. */
  second: string;
  result: string;
  count: number;
  /** AC skill id (0: none). */
  skill: number;
  difficulty: number;
  id: number;
}

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'packages/renderer/src/agent/macro/crafts');
const KEEP_SKILLS = new Set([0, 37, 38, 39]);

function sqlFiles(dir: string): string[] {
  const out: string[] = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out.push(...sqlFiles(p));
    else if (p.endsWith('.sql')) out.push(p);
  }
  return out;
}

/** ACE-layout recipe SQL: the recipe row (skill, difficulty, success wcid /* name *\/, amount) and its cook_book pairs. */
export function parseRecipeSql(text: string): CraftRecipe[] {
  const r = /INSERT INTO `recipe` \([^)]*\)\s*VALUES \((\d+), *\d+, *(\d+)[^,]*, *(\d+), *\d+, *(\d+) *(?:\/\* *(.*?) *\*\/)?, *(\d+),/.exec(text);
  if (!r) return [];
  const [, id, skill, difficulty, wcid, name, amount] = r;
  if (Number(wcid) === 0 || !name) return [];
  const book = /INSERT INTO `cook_book` \([^)]*\)\s*VALUES ([\s\S]*?);/.exec(text);
  if (!book) return [];
  const pairs = [...book[1].matchAll(/\(\d+, *\d+ *\/\* *(.*?) *\*\/, *\d+ *\/\* *(.*?) *\*\/,/g)];
  return pairs.map(([, first, second]) => ({ first, second, result: name, count: Number(amount), skill: Number(skill), difficulty: Number(difficulty), id: Number(id) }));
}

function fromSqlTree(dir: string): CraftRecipe[] {
  return sqlFiles(dir).flatMap((f) => parseRecipeSql(readFileSync(f, 'utf8')));
}

function fromClassicAce(): CraftRecipe[] {
  const pw = execFileSync('docker', ['exec', 'classicace-db', 'printenv', 'MYSQL_ROOT_PASSWORD'], { encoding: 'utf8' }).trim();
  const sql = (q: string): string[][] => execFileSync('docker', ['exec', 'classicace-db', 'mysql', '-uroot', `-p${pw}`, '-N', '-B', 'ace_world_customdm', '-e', q], { encoding: 'utf8', maxBuffer: 64 << 20 })
    .trim().split('\n').filter(Boolean).map((l) => l.split('\t'));
  // Two plain reads (a three-way join on the names table runs for minutes there): the pairs, then every name.
  const pairs = sql('SELECT r.id, r.skill, r.difficulty, r.success_Amount, r.success_W_C_I_D, c.source_W_C_I_D, c.target_W_C_I_D FROM recipe r JOIN cook_book c ON c.recipe_Id = r.id WHERE r.success_W_C_I_D <> 0');
  const names = new Map(sql('SELECT object_Id, value FROM weenie_properties_string WHERE type = 1').map(([id, v]) => [id, v]));
  return pairs.flatMap(([id, skill, difficulty, count, res, src, tgt]) => {
    const [result, first, second] = [names.get(res), names.get(src), names.get(tgt)];
    return result && first && second ? [{ first, second, result, count: Number(count), skill: Number(skill), difficulty: Number(difficulty), id: Number(id) }] : [];
  });
}

function write(era: string, all: CraftRecipe[]): void {
  const kept = all.filter((x) => KEEP_SKILLS.has(x.skill)).sort((a, b) => a.id - b.id || a.first.localeCompare(b.first));
  // Compact: [first, second, result, count, skill, difficulty, id] rows.
  const rows = kept.map((x) => [x.first, x.second, x.result, x.count, x.skill, x.difficulty, x.id]);
  // A module exporting the table as one JSON string (cheap to type-check; the bundle splits it into its own chunk).
  writeFileSync(join(OUT, `${era}.ts`), `// Generated by tools/build-craft-tables.ts from this era's world data; do not edit.\nexport default ${JSON.stringify(JSON.stringify(rows))};\n`);
  console.log(`${era}: ${kept.length} recipes kept of ${all.length}`);
}

// Run only as a script (tests import parseRecipeSql without regenerating anything).
const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename);
const want = process.argv.slice(2);
const eras = !isMain ? [] : want.length ? want : ['eol', 'ac1999', 'dm'];
for (const era of eras) {
  if (era === 'eol') write('eol', fromSqlTree(join(ROOT, 'world-db-raw/ACE-World-16PY/Database/3-Core/4 CraftTable')));
  else if (era === 'ac1999') write('ac1999', fromSqlTree(join(ROOT, 'reference/ac1999/Server/Database/AC1999-World/3-Core/4 CraftTable')));
  else if (era === 'dm') write('dm', fromClassicAce());
}
