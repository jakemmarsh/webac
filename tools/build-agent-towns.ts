/**
 * Generate the agent's 1999 town table (packages/renderer/src/agent/towns1999.ts) from the 1999 map marker table
 * and the 1999 cell.dat (tools/lib/agent-towns.ts says how). Rerun after tools/build-map-markers.ts ac1999.
 *
 *   npx tsx tools/build-agent-towns.ts
 */
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { DatDatabase } from '../packages/dat-parser/src/DatDatabase.ts';
import { FileDatBytes } from '../packages/dat-parser/src/node/FileDatBytes.ts';
import { ac1999CellOverlay } from '../packages/dat-parser/src/era1999/Ac1999Overlay.ts';
import markers1999 from '../packages/renderer/src/ui/maps/markers/ac1999.ts';
import { buildingCounter, deriveAgentTowns, townRowsOfMarkerTable } from './lib/agent-towns.ts';

const ROOT = resolve(import.meta.dirname, '..');

const cell = new DatDatabase(new FileDatBytes(join(ROOT, 'dat-sets/ac1999-retail/cell.dat')));
cell.setOverlay(ac1999CellOverlay());
const towns = deriveAgentTowns(townRowsOfMarkerTable(markers1999), buildingCounter(cell));
const out = `// Generated by tools/build-agent-towns.ts from the 1999 map marker table (ui/maps/markers/ac1999.ts) and the
// 1999 cell.dat; do not edit. [name, NS, EW]
export const AC1999_TOWN_ROWS: readonly (readonly [string, number, number])[] = [
${towns.map((t) => `  [${JSON.stringify(t.name)}, ${t.ns}, ${t.ew}],`).join('\n')}
];
`;
writeFileSync(join(ROOT, 'packages/renderer/src/agent/towns1999.ts'), out);
console.log(`${towns.length} towns`);
